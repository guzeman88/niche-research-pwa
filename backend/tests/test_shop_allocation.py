def test_delayed_mature_window_uses_reviews_after_counter_end_without_extrapolating():
    end = AT - timedelta(days=7)
    start = end - timedelta(days=7)
    item = product(count=7, start=start + timedelta(days=7), end=AT)
    result = allocate('7', counters(start=start, end=end), [item], AT,
                      {'central_lag_days': 7})
    assert result['products'][0]['review_count'] == 7
    assert result['products'][0]['review_coverage_fraction'] == 1
    assert result['window']['end'] == end.isoformat()


