def test_output_is_deterministic_and_every_numeric_output_is_finite():
    result = allocate('7', counters(), [product('1', 7), product('2', 3)], AT)
    assert result == allocate('7', counters(), [product('1', 7), product('2', 3)], AT)
    def finite(value):
        if isinstance(value, dict):
            return all(finite(v) for v in value.values())
        if isinstance(value, list):
            return all(finite(v) for v in value)
        return math.isfinite(value) if isinstance(value, float) else True
    assert finite(result)


def simulation_report():
    """Reproducible constructed recovery/failure examples for the runbook.

    No random search, provider estimates, real outcomes or accuracy claim. The
    final case deliberately violates the central review-lag assumption; it shows
    why sensitivity bands must not be presented as statistical confidence.
    """
    def summarize(result, truth):
        predictions = [p['value'] for p in result['products']]
        known = all(value is not None for value in predictions)
        errors = [abs(value - actual) for value, actual in zip(predictions, truth)] if known else []
        return {'truth': truth, 'predictions': predictions,
                'unobserved': result['unobserved']['value'],
                'mae': sum(errors) / len(errors) if errors else None,
                'wape': sum(errors) / sum(truth) if errors else None,
                'within_5_percent': sum(error <= .05 * actual for error, actual in zip(errors, truth)) if known else 0,
                'cases': len(truth), 'status': result['status'],
                'full_feasible_ranges_contain_truth': all(p['feasible_low'] <= actual <= p['feasible_high'] for p, actual in zip(result['products'], truth)),
                'mass_reconciled': sum(value or 0 for value in predictions) + result['unobserved']['value'] == pytest.approx(10000)}
    dense = allocate('simulation', counters(10000), [product('1', 700), product('2', 300)], AT,
                     {'catalog_complete': True})
    missing = allocate('simulation', counters(10000), [product('1', 700)], AT)
    absent = allocate('simulation', counters(10000), [product('1', 700, coverage=False)], AT)
    matured_end = AT - timedelta(days=14)
    matured_start = matured_end - timedelta(days=7)
    matured = allocate('simulation', counters(10000, start=matured_start, end=matured_end),
                       [product('1', 300), product('2', 700)], AT,
                       {'catalog_complete': True, 'central_lag_days': 14, 'max_staleness_days': 30})
    # The current shop has reversed its product mix, but reviews arriving today
    # still describe the old mix. The zero-lag central model cannot identify it.
    lag_shift = summarize(dense, [3000, 7000])
    return {'constructed_fixed_rate_complete_catalog': summarize(dense, [7000, 3000]),
            'constructed_unobserved_product': summarize(missing, [7000]),
            'incomplete_review_response': summarize(absent, [7000]),
            'constructed_correct_matured_lag': summarize(matured, [3000, 7000]),
            'violated_lag_changing_product_mix': lag_shift,
            'independent_actual_sales_validation': False}


def test_simulation_report_shows_both_recovery_and_nonidentifiability():
    report = simulation_report()
    for key in ('constructed_fixed_rate_complete_catalog', 'constructed_correct_matured_lag'):
        assert report[key]['within_5_percent'] == 2
        assert report[key]['wape'] < .03
        assert report[key]['mass_reconciled']
    assert report['constructed_unobserved_product']['unobserved'] == pytest.approx(3000, rel=.03)
    assert report['incomplete_review_response']['predictions'] == [None]
    assert report['incomplete_review_response']['unobserved'] == 10000
    failure = report['violated_lag_changing_product_mix']
    assert failure['within_5_percent'] == 0 and failure['wape'] > .70
    assert failure['full_feasible_ranges_contain_truth']
    assert report['independent_actual_sales_validation'] is False
